pytestmark = pytest.mark.django_db
YEAR = examples.example_year()


def current(code: str):
    return specifications.current(Specification.objects.get(code=code))


def field(v, table: str, name: str):
    return v.tables.get(name=table).fields.get(name=name)


def soon(days: int):
    return timezone.localdate() + timedelta(days=days)


@pytest.fixture
def draft(cpuc_admin):
    return editor.start_draft(cpuc_admin, current("monthly"), "Monthly reports 2029", "The 2029 reporting changes")


def generated(v):
    return v.examples.get(slug=examples.GENERATED)


# --- generating


def test_a_new_draft_gets_a_generated_example_that_links_its_tables(draft):
    e = generated(draft)
    assert e.generated and set(e.rows) == {"Commitments", "Measure", "ProgramCost"}
    c, m, p = e.rows["Commitments"][0], e.rows["Measure"][0], e.rows["ProgramCost"][0]
    assert c["PA"] == p["PA"] == "PGE" and c["YearMonth"] == f"{YEAR}01" and p["PrgYear"] == str(YEAR)
    assert c["PrgID"] == m["PrgID"] == p["PrgID"]  # a key of one table is the same value in each
    assert m["ClaimYearQuarter"] == f"{YEAR}Q1" and m["NumUnits"] == "1"
    assert m["PreDesc"] == ""  # optional, with no example or default: left blank
    assert m["AC_Climate_Zone"]  # required and coded: a code from its list


def test_a_claims_example_has_no_vault_table_and_uses_the_modules_example_values(cpuc_admin):
    v = editor.start_draft(cpuc_admin, current("claims"), "Claims 2029", "why")
    rows = generated(v).rows
    assert not {"PII_Contact", "PII_Site"} & set(rows)  # personal information is never in an example
    assert rows["Site"][0]["SiteState"] == "CA" and rows["Claim"][0]["ClaimID"].startswith(f"PGE-{YEAR}")
    assert rows["Site"][0]["SiteID"] == rows["ClaimSite"][0]["SiteID"]


def test_a_fields_example_or_default_is_used_when_it_is_valid(cpuc_admin, draft):
    editor.change_field(cpuc_admin, field(draft, "Measure", "PreDesc"), example="Old T8 lamps", reason="An example")
    editor.change_field(cpuc_admin, field(draft, "Measure", "NumUnits"), default="12", reason="A default")
    e = examples.generate(cpuc_admin, draft, "Write it again")
    assert e.rows["Measure"][0]["PreDesc"] == "Old T8 lamps" and e.rows["Measure"][0]["NumUnits"] == "12"
    assert AuditEvent.objects.filter(action="specification.example_generated").exists()


# --- checking


@pytest.mark.parametrize("code", ["monthly", "budget_filing", "claims"])
def test_the_generated_example_passes_the_checks_a_filing_gets(cpuc_admin, code):
    v = editor.start_draft(cpuc_admin, current(code), "Example check", "why")
    examples.check_all(v)
    r = generated(v).report
    assert examples.rejects(r) == [], r["failing"]
    assert r["year"] == YEAR and not r["notes"]
    prefix = {"monthly": "MON", "budget_filing": "BUD", "claims": "CLM"}[code]
    assert {"rule_id": f"{prefix}-PRG", "met": True} in [{k: c[k] for k in ("rule_id", "met")} for c in r["reference"]]
    assert not examples.stale(v)


def test_a_rejected_record_stops_publishing(cpuc_admin, draft):
    e = generated(draft)
    rows = e.rows
    rows["Commitments"][0]["YTDCommittedFunds"] = "lots"
    rows["Measure"][0]["NumUnits"] = ""
    examples.replace_rows(cpuc_admin, e, rows, "Show a failure")
    e.refresh_from_db()
    failing = {(f["table"], f["field"], f["rule_id"]) for f in examples.rejects(e.report)}
    assert ("Measure", "NumUnits", "FIELD") in failing and ("Commitments", "YTDCommittedFunds", "MON-NUM") in failing
    editor.change_field(cpuc_admin, field(draft, "Commitments", "Comments"), guidance="Say what changed.", reason="Clearer")
    with pytest.raises(editor.EditError, match="The example Generated by CEDARS has .* rejected findings"):
        editor.publish(cpuc_admin, draft, effective_on=soon(20))  # checked again first, as the draft now stands
    examples.generate(cpuc_admin, draft, "Start again")
    assert editor.publish(cpuc_admin, draft, effective_on=soon(20)).status == "published"


def test_a_conditional_rule_no_record_meets_is_not_demonstrated(cpuc_admin):
    published = RuleSet.objects.create(code="monthly_test", label="Monthly test", effective_from=soon(-30))
    Rule.objects.create(rule_set=published, rule_id="Vtest01", severity="warning", table="Measure", field="NumUnits", kind="rule",
                        definition={"field": "NumUnits", "rule": "equals", "value": "1", "connector": "all",
                                    "conds": [["Measure", "PreDesc", "equals", "x"]]},
                        message="When PreDesc is x, NumUnits should equal 1", modules=["monthly"])  # fmt: skip
    RuleSet.objects.filter(pk=published.pk).update(status="published")
    doc = specifications.stored_starting("monthly")
    doc["version"]["name"] = "Monthly with a rule"
    base = specifications.load(doc, rule_set=RuleSet.objects.get(pk=published.pk))
    v = editor.start_draft(cpuc_admin, base, "Monthly reports 2029", "why")
    examples.check_all(v)
    assert [n["message"] for n in generated(v).report["not_shown"]] == ["When PreDesc is x, NumUnits should equal 1"]
    e = generated(v)
    rows = e.rows
    rows["Measure"][0]["PreDesc"] = "x"
    examples.replace_rows(cpuc_admin, e, rows, "Show the rule")
    e.refresh_from_db()
    assert e.report["not_shown"] == [] and not examples.rejects(e.report)


# --- following the fields


def test_an_example_follows_the_drafts_fields(cpuc_admin, draft):
    editor.add_field(cpuc_admin, draft, "Commitments", "ReportingNote", requirement="required", definition="A note", reason="why")
    editor.rename_field(cpuc_admin, field(draft, "Measure", "PreDesc"), "PreDescription", "The CPUC's name")
    editor.remove_field(cpuc_admin, field(draft, "Measure", "StdDesc"), "Not needed")
    assert examples.stale(draft)
    examples.check_all(draft)
    rows = generated(draft).rows
    assert rows["Commitments"][0]["ReportingNote"] == "Example" and "StdDesc" not in rows["Measure"][0]
    assert "PreDescription" in rows["Measure"][0] and "PreDesc" not in rows["Measure"][0]
    assert not examples.stale(draft)


def test_a_draft_takes_its_versions_examples(cpuc_admin, draft):
    e = generated(draft)
    rows = e.rows
    rows["Measure"][0]["PreDesc"] = "Kept"
    examples.replace_rows(cpuc_admin, e, rows, "An edit")
    editor.change_field(cpuc_admin, field(draft, "Commitments", "Comments"), guidance="Say what changed.", reason="Clearer")
    v = editor.publish(cpuc_admin, draft, effective_on=soon(20))
    later = editor.start_draft(cpuc_admin, v, "Monthly reports 2030", "why")
    assert [x.slug for x in later.examples.all()] == [examples.GENERATED]
    assert generated(later).rows["Measure"][0]["PreDesc"] == "Kept"


# --- the example's file


def test_an_example_loads_back_from_its_workbook_and_zip(cpuc_admin, draft):
    e = generated(draft)
    wb = load_workbook(io.BytesIO(downloads.example_xlsx(draft, e)))
    ws = wb["Measure"]
    header = [c.value for c in ws[1]]
    ws.cell(row=2, column=header.index("PreDesc") + 1, value="From the workbook")
    out = io.BytesIO()
    wb.save(out)
    rows = examples.read_file(draft, "example.xlsx", out.getvalue())
    assert rows["Measure"][0]["PreDesc"] == "From the workbook" and rows["Measure"][0]["NumUnits"] == "1"
    e = examples.replace_rows(cpuc_admin, e, rows, "Edited in Excel")
    assert e.rows["Measure"][0]["PreDesc"] == "From the workbook" and not examples.rejects(e.report)
    z = zipfile.ZipFile(io.BytesIO(downloads.example_zip(draft, e)))
    assert examples.read_file(draft, "example.zip", _zip({n: z.read(n) for n in z.namelist()}))["Measure"][0]["PreDesc"] == (
        "From the workbook"
    )
    with pytest.raises(examples.ExampleError, match="workbook"):
        examples.read_file(draft, "example.csv", b"a,b")


def _zip(files: dict) -> bytes:
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        for n, b in files.items():
            z.writestr(n, b)
    return out.getvalue()


def test_an_example_with_personal_information_is_refused(cpuc_admin, draft):
    e = generated(draft)
    rows = e.rows
    rows["Commitments"][0]["Comments"] = "Call Ana at 415-555-0123"
    with pytest.raises(editor.EditError, match="personal information.*Commitments.Comments"):
        examples.replace_rows(cpuc_admin, e, rows, "why")
    with pytest.raises(editor.EditError, match="Say why"):
        examples.replace_rows(cpuc_admin, e, generated(draft).rows, "")


# --- pages


def test_the_examples_page(client, cpuc_admin, draft):
    sign_in(client, cpuc_admin)
    url = reverse("specifications:edit_examples", args=["monthly", draft.slug])
    page = client.get(url).content.decode()
    assert 'id="example-generated"' in page and "Passes" in page and 'id="reference-generated"' in page and "MON-PRG" in page
    assert reverse("specifications:example", args=["monthly", draft.slug, "generated", "xlsx"]) in page
    r = client.post(reverse("specifications:generate_examples", args=["monthly", draft.slug]), {"reason": "Again"})
    assert r.status_code == 302 and r.url.endswith("#example-generated")
    rows = generated(draft).rows
    rows["Measure"][0]["NumUnits"] = "many"
    wb_bytes = _workbook(draft, rows)
    post = reverse("specifications:example_file", args=["monthly", draft.slug, "generated"])
    r = client.post(post, {"file": SimpleUploadedFile("e.xlsx", wb_bytes), "reason": "A failure"})
    assert r.status_code == 302
    page = client.get(url).content.decode()
    assert "Fails" in page and "NumUnits many" in page
    publish = client.get(reverse("specifications:edit_publish", args=["monthly", draft.slug])).content.decode()
    assert (
        "The example Generated by CEDARS has" in publish
        and reverse("specifications:edit_examples", args=["monthly", draft.slug]) in publish
    )


def _workbook(v, rows) -> bytes:
    from cedars.core import workbooks

    book = workbooks.Book("example")
    for t, rs in rows.items():
        cols = list(rs[0])
        book.sheet(t, cols, [[r[c] for c in cols] for r in rs])
    return book.save()
